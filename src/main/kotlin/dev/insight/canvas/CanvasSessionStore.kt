private val LOG = logger<CanvasSessionStore>()

/** A saved session as listed for the reader to pick one, without its cards. */
data class CanvasSessionEntry(val id: String, val rootPath: String, val title: String, val updated: Long, val cards: Int)

/**
 * Canvas sessions saved as one JSON file each in [directory]. Every call does file IO, so call it off the EDT. A
 * damaged, unreadable or newer-version file is skipped and logged; a failed write is logged. Nothing throws to callers.
 */
class CanvasSessionStore(private val directory: Path) {
    /** Saved sessions, newest first; only those of [rootPath] when it is set. */
    fun list(rootPath: String? = null): List<CanvasSessionEntry> {
        val files = runCatching { if (Files.isDirectory(directory)) directory.listDirectoryEntries("*$SUFFIX") else emptyList() }
            .onFailure { rethrowCancellation(it); LOG.warn("Could not list canvas sessions in $directory", it) }.getOrDefault(emptyList())
        return files.filter { it.isRegularFile() }.mapNotNull { file -> read(file)?.let(::entry) }
            .filter { rootPath == null || it.rootPath == rootPath }
            .sortedWith(compareByDescending<CanvasSessionEntry> { it.updated }.thenBy { it.id })
    }

    /** The saved session [id], or null when it is missing or unreadable. */
    fun load(id: String): CanvasSession? = file(id)?.let(::read)?.let(::decode)

    /** Saves [session] atomically, replacing an earlier save; returns whether it was written. */
    fun save(session: CanvasSession): Boolean = synchronized(this) {
        val file = file(session.id) ?: return false
        runCatching {
            Files.createDirectories(directory)
            // Sessions hold the reader's chats; keep them out of Git without editing the project's ignore rules.
            val ignore = directory.resolve(".gitignore")
            if (!Files.exists(ignore)) runCatching { Files.writeString(ignore, "*\n", StandardOpenOption.CREATE_NEW) }
                .onFailure { rethrowCancellation(it); LOG.debug("Could not create $ignore", it) }
            val temp = Files.createTempFile(directory, "canvas-", ".tmp")
            try {
                Files.writeString(temp, json.toJson(encode(session)))
                try {
                    Files.move(temp, file, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
                } catch (e: AtomicMoveNotSupportedException) {
                    LOG.debug("Atomic move not supported; falling back to a plain move", e)
                    Files.move(temp, file, StandardCopyOption.REPLACE_EXISTING)
                }
            } finally {
                Files.deleteIfExists(temp)
            }
        }.onFailure { rethrowCancellation(it); LOG.warn("Could not save canvas session ${session.id}", it) }.isSuccess
    }

    /** Deletes the saved session [id]; returns whether a file was removed. */
    fun delete(id: String): Boolean = synchronized(this) {
        val file = file(id) ?: return false
        runCatching { Files.deleteIfExists(file) }
            .onFailure { rethrowCancellation(it); LOG.warn("Could not delete canvas session $id", it) }.getOrDefault(false)
    }

    /** Ids are generated by [newCanvasId]; anything else could name a file outside the directory. */
    private fun file(id: String): Path? = if (ID.matches(id)) directory.resolve("$id$SUFFIX") else {
        LOG.warn("Ignoring canvas session with invalid id '$id'")
        null
    }

    private fun read(file: Path): JsonObject? = runCatching {
        val root = JsonParser.parseString(Files.readString(file)).asJsonObject
        val version = root["version"]?.asInt
        if (version != VERSION) {
            LOG.info("Skipping canvas session $file of version $version")
            null
        } else root.getAsJsonObject("session")
    }.onFailure {
        rethrowCancellation(it)
        if (it is NoSuchFileException) LOG.debug("No canvas session at $file") else LOG.warn("Could not read canvas session $file", it)
    }.getOrNull()

    private fun entry(stored: JsonObject): CanvasSessionEntry? = decode(stored)?.let {
        CanvasSessionEntry(it.id, it.rootPath, it.title, it.updated, it.cards.size)
    }

    private fun encode(session: CanvasSession): JsonObject = JsonObject().apply {
        addProperty("version", VERSION)
        add("session", json.toJsonTree(StoredSession(session.id, session.rootPath, session.title, session.created, session.updated,
            session.cards.map { card ->
                StoredCard(card.id, card.parentId, card.kind.name, card.anchor.startOffset, card.anchor.endOffset, card.anchor.line,
                    card.symbol?.let { StoredSymbol(it.filePath, it.name, it.kind, it.container, it.offset, it.line) },
                    card.filePath, card.firstLine, card.text, card.textTruncated, card.summary, card.summaryError,
                    card.folded.map { it.name }.sorted(), null, null, card.wholeFile,
                    card.chats.map { StoredChat(it.id, it.title, it.messages.map { m -> StoredMessage(m.role.name, m.text) }, it.draft) },
                    card.activeChatId)
            }, session.view.zoom, session.view.x, session.view.y)))
    }

    /** Lenient: missing optional fields take their defaults, unknown enum names are dropped, and a card without a parent is dropped. */
    private fun decode(stored: JsonObject): CanvasSession? = runCatching {
        val session = json.fromJson(stored, StoredSession::class.java)
        val id = session.id?.takeIf { ID.matches(it) } ?: error("Session without a valid id")
        val rootPath = session.rootPath ?: error("Session $id without a root path")
        val cards = mutableListOf<CanvasCard>()
        for (card in session.cards.orEmpty()) {
            val cardId = card?.id ?: continue
            // Parents are saved before their children; an orphan has nowhere to be drawn.
            if (card.parentId != null && cards.none { it.id == card.parentId }) continue
            val kind = enumOrNull<CardKind>(card.kind) ?: continue
            val symbol = card.symbol?.let { symbol ->
                SymbolRef(symbol.filePath ?: return@let null, symbol.name ?: return@let null, symbol.kind.orEmpty(), symbol.container.orEmpty(),
                    symbol.offset ?: -1, symbol.line ?: -1)
            }
            if (kind == CardKind.SYMBOL && symbol == null) continue
            val chats = card.chats.orEmpty().filterNotNull().mapNotNull { chat ->
                val chatId = chat.id?.takeIf { it.isNotBlank() } ?: return@mapNotNull null
                CanvasChat(chatId, chat.title ?: "Chat", decodeMessages(chat.messages), chat.draft.orEmpty())
            }.distinctBy { it.id }.ifEmpty {
                listOf(CanvasChat(messages = decodeMessages(card.messages), draft = card.draft.orEmpty()))
            }
            cards += CanvasCard(cardId, card.parentId, kind, CardAnchor(card.start ?: 0, card.end ?: 0, card.line ?: 0), symbol,
                card.filePath.orEmpty(), card.firstLine ?: 0, card.text.orEmpty(), card.truncated ?: false, card.summary, card.summaryError,
                card.folded.orEmpty().mapNotNullTo(linkedSetOf()) { enumOrNull<CardSection>(it) },
                chats, card.activeChatId?.takeIf { id -> chats.any { it.id == id } } ?: chats.first().id, card.wholeFile ?: false)
        }
        val created = session.created ?: 0L
        CanvasSession(id, rootPath, session.title ?: rootPath.substringAfterLast('/'), created, session.updated ?: created, cards,
            CanvasView(session.zoom ?: 1.0, session.x ?: 0, session.y ?: 0))
    }.onFailure { rethrowCancellation(it); LOG.warn("Could not decode canvas session", it) }.getOrNull()

    private fun decodeMessages(messages: List<StoredMessage?>?): List<SavedMessage> = messages.orEmpty().mapNotNull { message ->
        SavedMessage(enumOrNull<ChatRole>(message?.role) ?: return@mapNotNull null, message?.text ?: return@mapNotNull null)
    }

    // The stored shape, apart from the domain types so they can change without breaking saved files. Gson leaves
    // missing fields null, whatever Kotlin declares, so every field is nullable.
    private class StoredSession(val id: String?, val rootPath: String?, val title: String?, val created: Long?, val updated: Long?,
        val cards: List<StoredCard?>?, val zoom: Double?, val x: Int?, val y: Int?)
    private class StoredCard(val id: String?, val parentId: String?, val kind: String?, val start: Int?, val end: Int?, val line: Int?,
        val symbol: StoredSymbol?, val filePath: String?, val firstLine: Int?, val text: String?, val truncated: Boolean?,
        val summary: String?, val summaryError: String?, val folded: List<String?>?, val messages: List<StoredMessage?>?, val draft: String?,
        val wholeFile: Boolean?, val chats: List<StoredChat?>?, val activeChatId: String?)
    private class StoredChat(val id: String?, val title: String?, val messages: List<StoredMessage?>?, val draft: String?)
    private class StoredSymbol(val filePath: String?, val name: String?, val kind: String?, val container: String?, val offset: Int?, val line: Int?)
    private class StoredMessage(val role: String?, val text: String?)

    companion object {
        /** Bump when the stored shape changes incompatibly; older files are then skipped rather than misread. */
        private const val VERSION = 1
        private const val SUFFIX = ".json"
        private val ID = Regex("[A-Za-z0-9_-]{1,64}")
        private val json = GsonBuilder().disableHtmlEscaping().create()

        /** Below the project's `.insight` directory, beside the review cache. */
        const val DIRECTORY = "canvas-sessions"

        /** The store of [project], or null when it has no base directory. */
        fun forProject(project: Project): CanvasSessionStore? =
            project.basePath?.let { CanvasSessionStore(Path.of(it, ".insight", DIRECTORY)) }

        private inline fun <reified E : Enum<E>> enumOrNull(name: String?): E? = enumValues<E>().firstOrNull { it.name == name }
    }
}

/**
 * Saves the latest requested state of a session at most once per [delayMs], so dragging, scrolling and typing do not
 * write on every change. [request] may be called from any thread (normally the EDT, after each model change); saves
 * run in [scope] on [context]. Call [flush] when the view closes so the last change is not lost.
 */
class CanvasSessionAutosave(private val store: CanvasSessionStore, private val scope: CoroutineScope, private val delayMs: Long = 1_000,
    private val context: CoroutineContext = Dispatchers.IO) {
    private val pending = AtomicReference<CanvasSession?>(null)
    private val lock = Any()
    private var job: Job? = null
    /** Orders writes: the session taken from [pending] last is always written last. */
    private val writing = Any()

    /** Schedules saving [session]; a later request before the save replaces it. */
    fun request(session: CanvasSession) {
        pending.set(session)
        synchronized(lock) {
            if (job?.isActive == true) return
            job = scope.launch(context) {
                delay(delayMs)
                write()
            }
        }
    }

    /** True while a requested state has not been written yet. */
    val dirty: Boolean get() = pending.get() != null

    /** Writes a pending state now, on the calling thread; the file write is small, so the EDT may call it when closing. */
    fun flush() {
        synchronized(lock) { job?.cancel(); job = null }
        write()
    }

    /** Waits for a scheduled save, for tests. */
    internal suspend fun join() {
        synchronized(lock) { job }?.join()
    }

    private fun write() = synchronized(writing) {
        pending.getAndSet(null)?.let(store::save)
    }
}

private fun rethrowCancellation(e: Throwable) {
    if (e is CancellationException || e is ProcessCanceledException) throw e
}
